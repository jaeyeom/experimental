package main

import "flag"

// parseInterspersed parses fs's flags anywhere in args, before or after
// the positional arguments, and returns the positional arguments in
// order. "--" ends flag parsing: everything after it is positional.
func parseInterspersed(fs *flag.FlagSet, args []string) ([]string, error) {
	var pos []string
	for {
		if err := fs.Parse(args); err != nil {
			return nil, err //nolint:wrapcheck // flag already printed it
		}
		rest := fs.Args()
		if len(rest) == 0 {
			return pos, nil
		}
		if used := len(args) - len(rest); used > 0 && args[used-1] == "--" {
			return append(pos, rest...), nil
		}
		pos = append(pos, rest[0])
		args = rest[1:]
	}
}

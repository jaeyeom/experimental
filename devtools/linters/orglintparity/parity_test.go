func TestParse(t *testing.T) {
	in := "a.org:3: link-to-local-file: Link to non-existent local file \"x: y\"\n\nb/c.org:10: duplicate-name: Duplicate NAME \"n\"\n"
	got, err := Parse(strings.NewReader(in))
	if err != nil {
		t.Fatal(err)
	}
	want := []Finding{
		{"a.org", 3, "link-to-local-file", "Link to non-existent local file \"x: y\""},
		{"b/c.org", 10, "duplicate-name", "Duplicate NAME \"n\""},
	}
	if len(got) != len(want) {
		t.Fatalf("got %v, want %v", got, want)
	}
	for i := range want {
		if got[i] != want[i] {
			t.Errorf("finding %d: got %v, want %v", i, got[i], want[i])
		}
		if got[i].String() != strings.Split(in, "\n")[map[int]int{0: 0, 1: 2}[i]] {
			t.Errorf("String() = %q", got[i].String())
		}
	}
}

func TestParseRejectsGarbage(t *testing.T) {
	if _, err := Parse(strings.NewReader("not a finding\n")); err == nil {
		t.Fatal("want error")
	}
}

func TestDiff(t *testing.T) {
	emacs := []Finding{
		{"a.org", 1, "c1", "m1"},
		{"a.org", 2, "c2", "m2"},
		{"a.org", 5, "c3", "m3"},
	}
	gol := []Finding{
		{"a.org", 1, "c1", "m1"},
		{"a.org", 7, "c3", "m3"},
		{"a.org", 9, "c4", "m4"},
	}
	r := Diff(emacs, gol)
	if len(r.Missed) != 1 || r.Missed[0].Checker != "c2" {
		t.Errorf("Missed = %v", r.Missed)
	}
	if len(r.Extra) != 1 || r.Extra[0].Checker != "c4" {
		t.Errorf("Extra = %v", r.Extra)
	}
	if len(r.LineDiffs) != 1 || r.LineDiffs[0].Want.Line != 5 || r.LineDiffs[0].Got.Line != 7 {
		t.Errorf("LineDiffs = %v", r.LineDiffs)
	}
	if r.Empty() {
		t.Error("Empty() = true")
	}
	if !Diff(emacs, emacs).Empty() {
		t.Error("identical findings should be empty")
	}
}

func TestFormatSortsAndRoundTrips(t *testing.T) {
	fs := []Finding{{"b.org", 1, "c", "m"}, {"a.org", 9, "c", "m"}, {"a.org", 2, "c", "m"}}
	out := Format(fs)
	if want := "a.org:2: c: m\na.org:9: c: m\nb.org:1: c: m\n"; out != want {
		t.Errorf("Format = %q", out)
	}
	back, err := Parse(strings.NewReader(out))
	if err != nil || len(back) != 3 {
		t.Fatalf("round trip: %v %v", back, err)
	}
}

// Goldens are generated by Emacs through org-lint-parity -update. This test
// only checks they are present and well formed, so it never needs Emacs.
func TestFixturesHaveGoldens(t *testing.T) {
	orgs, err := filepath.Glob("../testdata/orglint/*.orgtest")
	if err != nil || len(orgs) == 0 {
		t.Fatalf("no fixtures: %v", err)
	}
	for _, org := range orgs {
		golden := GoldenPath(org)
		data, err := os.ReadFile(golden)
		if err != nil {
			t.Errorf("%s: missing golden: %v", org, err)
			continue
		}
		fs, err := Parse(strings.NewReader(string(data)))
		if err != nil {
			t.Errorf("%s: %v", golden, err)
			continue
		}
		if len(fs) == 0 {
			t.Errorf("%s: fixture triggers nothing", org)
		}
		for _, f := range fs {
			if f.File != filepath.Base(org) {
				t.Errorf("%s: finding for %q", golden, f.File)
			}
		}
	}
}

// ProjectionManifestVersion is the schema version of .projection-manifest.json.
const ProjectionManifestVersion = 1

const manifestFileName = ".projection-manifest.json"

// ExportOptions configures deterministic DB-to-Markdown projection.
type ExportOptions struct {
	AllowGit bool
	Actor    Actor
	Getenv   func(string) string
	Now      func() time.Time
}

// ExportReport summarizes the files written, unchanged, and removed by Export.
type ExportReport struct {
	Profile   string `json:"profile"`
	OutDir    string `json:"outDir"`
	Written   int    `json:"written"`
	Unchanged int    `json:"unchanged"`
	Removed   int    `json:"removed"`
}

// ProjectionManifest records every file generated by Export so subsequent runs
// can skip unchanged files and remove stale files.
type ProjectionManifest struct {
	Version     int                      `json:"version"`
	Profile     string                   `json:"profile"`
	GeneratedAt time.Time                `json:"generatedAt"`
	Files       map[string]ManifestEntry `json:"files"`
}

// ManifestEntry describes one projected Markdown file in ProjectionManifest.
type ManifestEntry struct {
	SHA256   string `json:"sha256"`
	EntityID string `json:"entityId,omitempty"`
	Size     int64  `json:"size"`
}

type projectedFile struct {
	relPath  string
	entityID string
	content  []byte
}

type exportedEntity struct {
	entity       Entity
	vaultName    string
	aliases      []string
	facts        []Fact
	noteBlocks   []NoteBlock
	links        []EntityLink
	contacts     *ContactsAttributes
	routineState map[string]string
}

type entityFrontmatter struct {
	Title       string   `yaml:"title"`
	Aliases     []string `yaml:"aliases,omitempty"`
	GeneratedBy string   `yaml:"generated_by"`
	Profile     string   `yaml:"profile"`
	EntityID    string   `yaml:"entity_id"`
}

// Export renders a deterministic, profile-scoped Aside-compatible Markdown tree
// into outDir, writing .projection-manifest.json and removing stale files.
func Export(ctx context.Context, svc *Service, outDir string, opts ExportOptions) (ExportReport, error) {
	if svc == nil {
		return ExportReport{}, fmt.Errorf("service is required")
	}
	if !svc.policy.HasCapability(CapabilityExport) {
		return ExportReport{}, fmt.Errorf("%w: profile %q lacks capability %q", ErrForbidden, svc.policy.name, CapabilityExport)
	}
	if outDir == "" {
		return ExportReport{}, fmt.Errorf("output directory is required")
	}
	absOut, err := filepath.Abs(outDir)
	if err != nil {
		return ExportReport{}, fmt.Errorf("resolve output directory %q: %w", outDir, err)
	}
	if !opts.AllowGit {
		if err := RejectGitWorkTree(absOut); err != nil {
			return ExportReport{}, err
		}
	}

	getenv := opts.Getenv
	if getenv == nil {
		getenv = os.Getenv
	}
	nowFn := opts.Now
	if nowFn == nil {
		nowFn = time.Now
	}

	entities, events, err := collectExportData(ctx, svc, opts.Actor, getenv, nowFn)
	if err != nil {
		return ExportReport{}, err
	}

	files, err := buildProjectedFiles(svc.policy, entities, events)
	if err != nil {
		return ExportReport{}, err
	}

	return syncProjectedFiles(absOut, svc.policy.name, files, nowFn().UTC())
}

func collectExportData(ctx context.Context, svc *Service, actor Actor, getenv func(string) string, now func() time.Time) ([]*exportedEntity, []EpisodicEvent, error) {
	byID := make(map[string]*exportedEntity)
	var order []string
	var allEvents []EpisodicEvent

	for _, vaultName := range svc.order {
		v := svc.vaults[vaultName]
		if err := collectVaultEntities(ctx, svc, v, vaultName, byID, &order, getenv, now); err != nil {
			return nil, nil, err
		}
		events, err := svc.queryVaultEvents(ctx, v, EventFilter{})
		if err != nil {
			return nil, nil, err
		}
		for i := range events {
			events[i].Vault = vaultName
		}
		allEvents = append(allEvents, events...)
		if err := svc.logAccess(ctx, v, actor, "export", ""); err != nil {
			return nil, nil, err
		}
	}

	slices.Sort(order)
	entities := make([]*exportedEntity, 0, len(order))
	for _, id := range order {
		ee := byID[id]
		normalizeExportedEntity(ee)
		entities = append(entities, ee)
	}

	slices.SortFunc(allEvents, func(a, b EpisodicEvent) int {
		if c := strings.Compare(b.EventDate, a.EventDate); c != 0 {
			return c
		}
		if !a.OccurredAt.Equal(b.OccurredAt) {
			if b.OccurredAt.After(a.OccurredAt) {
				return 1
			}
			return -1
		}
		return strings.Compare(b.ID, a.ID)
	})

	return entities, allEvents, nil
}

func collectVaultEntities(ctx context.Context, svc *Service, v *Vault, vaultName string, byID map[string]*exportedEntity, order *[]string, getenv func(string) string, now func() time.Time) error {
	compsJSON, sensJSON, err := svc.allowedScopeJSON()
	if err != nil {
		return err
	}
	entities, err := scanEntityRows(ctx, v.db,
		`SELECT id, kind, slug, title, contacts_ref, default_compartment, sensitivity, summary, pinned_l1, created_at, updated_at, archived_at
		FROM entities
		WHERE archived_at IS NULL
		  AND default_compartment IN (SELECT value FROM json_each(?))
		  AND sensitivity IN (SELECT value FROM json_each(?))
		ORDER BY id`,
		compsJSON, sensJSON,
	)
	if err != nil {
		return err
	}

	for _, e := range entities {
		if err := collectSingleVaultEntity(ctx, svc, v, vaultName, e, byID, order, getenv, now); err != nil {
			return err
		}
	}
	return nil
}

func collectSingleVaultEntity(
	ctx context.Context,
	svc *Service,
	v *Vault,
	vaultName string,
	e Entity,
	byID map[string]*exportedEntity,
	order *[]string,
	getenv func(string) string,
	now func() time.Time,
) error {
	aliases, err := loadAliases(ctx, v.db, e.ID)
	if err != nil {
		return err
	}
	facts, err := svc.queryVaultFacts(ctx, v, FactFilter{Vault: vaultName, EntityID: e.ID})
	if err != nil {
		return err
	}
	notes, err := svc.queryVaultNoteBlocks(ctx, v, e.ID)
	if err != nil {
		return err
	}
	links, err := svc.queryEntityLinks(ctx, v.db, e.ID)
	if err != nil {
		return err
	}

	ee, exists := byID[e.ID]
	if !exists {
		ee = &exportedEntity{entity: e, vaultName: vaultName}
		byID[e.ID] = ee
		*order = append(*order, e.ID)
	}
	ee.aliases = append(ee.aliases, aliases...)
	ee.facts = append(ee.facts, facts...)
	ee.noteBlocks = append(ee.noteBlocks, notes...)
	ee.links = append(ee.links, links...)

	if ee.contacts == nil && e.Kind == "person" && e.ContactsRef != "" && v.config.ContactsConfig != "" {
		attrs, ok, err := loadContactsAttributes(v.config.ContactsConfig, e.ContactsRef, getenv, now)
		if err != nil {
			return err
		}
		if ok {
			ee.contacts = &attrs
		}
	}
	if e.Kind == "routine" {
		return loadRoutineEntityState(ctx, v, e.Slug, ee)
	}
	return nil
}

func loadRoutineEntityState(ctx context.Context, v *Vault, slug string, ee *exportedEntity) error {
	rstate, err := v.AllRoutineState(ctx, slug)
	if err != nil {
		return err
	}
	if len(rstate) == 0 {
		return nil
	}
	if ee.routineState == nil {
		ee.routineState = make(map[string]string, len(rstate))
	}
	for k, val := range rstate {
		ee.routineState[k] = val
	}
	return nil
}

func normalizeExportedEntity(ee *exportedEntity) {
	slices.Sort(ee.aliases)
	ee.aliases = slices.Compact(ee.aliases)

	slices.SortFunc(ee.facts, func(a, b Fact) int {
		if c := strings.Compare(a.Key, b.Key); c != 0 {
			return c
		}
		if c := strings.Compare(a.Compartment, b.Compartment); c != 0 {
			return c
		}
		if c := strings.Compare(a.ValueJSON, b.ValueJSON); c != 0 {
			return c
		}
		return strings.Compare(a.ID, b.ID)
	})

	slices.SortFunc(ee.links, func(a, b EntityLink) int {
		if c := strings.Compare(a.Relation, b.Relation); c != 0 {
			return c
		}
		if c := strings.Compare(a.FromEntityID, b.FromEntityID); c != 0 {
			return c
		}
		return strings.Compare(a.ToEntityID, b.ToEntityID)
	})

	slices.SortFunc(ee.noteBlocks, func(a, b NoteBlock) int {
		if a.SortOrder != b.SortOrder {
			return a.SortOrder - b.SortOrder
		}
		if c := strings.Compare(a.SectionKey, b.SectionKey); c != 0 {
			return c
		}
		return strings.Compare(a.Heading, b.Heading)
	})
}

func buildProjectedFiles(policy Policy, entities []*exportedEntity, events []EpisodicEvent) ([]projectedFile, error) {
	var files []projectedFile

	files = append(files, projectedFile{
		relPath: "MEMORY.md",
		content: renderMemoryIndex(entities),
	})
	files = append(files, projectedFile{
		relPath: "TAXONOMY.md",
		content: renderTaxonomy(policy),
	})

	var userEntities []*exportedEntity
	for _, ee := range entities {
		if ee.entity.Kind == "user" {
			userEntities = append(userEntities, ee)
		}
		content, err := renderEntityMarkdown(policy.name, ee)
		if err != nil {
			return nil, err
		}
		files = append(files, projectedFile{
			relPath:  entityRelPath(ee.entity),
			entityID: ee.entity.ID,
			content:  content,
		})
	}

	if len(userEntities) > 0 {
		files = append(files, projectedFile{
			relPath:  "USER.md",
			entityID: userEntities[0].entity.ID,
			content:  renderUserMarkdown(userEntities),
		})
	}

	files = append(files, renderEpisodicFiles(events)...)
	return files, nil
}

func kindPluralDir(kind string) string {
	switch kind {
	case "person":
		return "people"
	case "company":
		return "companies"
	case "site":
		return "sites"
	case "project":
		return "projects"
	case "concept":
		return "concepts"
	case "user":
		return "users"
	case "agent":
		return "agent"
	case "routine":
		return "routines"
	default:
		return kind + "s"
	}
}

func entityRelPath(e Entity) string {
	if e.Kind == "routine" {
		return "routines/" + e.Slug + "/MEMORY.md"
	}
	return kindPluralDir(e.Kind) + "/" + e.Slug + ".md"
}

func renderMemoryIndex(entities []*exportedEntity) []byte {
	var b strings.Builder
	b.WriteString("# Memory Index\n\n")
	pinned := 0
	for _, ee := range entities {
		if !ee.entity.PinnedL1 {
			continue
		}
		pinned++
		rel := entityRelPath(ee.entity)
		if ee.entity.Summary != "" {
			fmt.Fprintf(&b, "- [%s](%s) (`%s`): %s\n", ee.entity.Title, rel, ee.entity.ID, ee.entity.Summary)
		} else {
			fmt.Fprintf(&b, "- [%s](%s) (`%s`)\n", ee.entity.Title, rel, ee.entity.ID)
		}
	}
	if pinned == 0 {
		b.WriteString("_No pinned entities._\n")
	}
	return []byte(b.String())
}

func renderTaxonomy(policy Policy) []byte {
	var b strings.Builder
	b.WriteString("# Taxonomy Reference\n\n")
	b.WriteString("_Generated read-only by memstore. Do not edit manually._\n\n")
	b.WriteString("## Entity Directories\n\n")
	for _, pair := range []struct{ kind, dir string }{
		{"person", "people/"},
		{"company", "companies/"},
		{"site", "sites/"},
		{"project", "projects/"},
		{"concept", "concepts/"},
		{"user", "users/"},
		{"agent", "agent/"},
		{"routine", "routines/"},
	} {
		fmt.Fprintf(&b, "- `%s` -> `%s`\n", pair.kind, pair.dir)
	}
	b.WriteString("\n## Profile Scope\n\n")
	fmt.Fprintf(&b, "- **Profile**: `%s`\n", policy.name)
	fmt.Fprintf(&b, "- **Vaults**: %s\n", strings.Join(policy.AllowedVaults(), ", "))
	fmt.Fprintf(&b, "- **Compartments**: %s\n", strings.Join(policy.AllowedCompartments(), ", "))
	fmt.Fprintf(&b, "- **Max Sensitivity**: `%s`\n", policy.MaxSensitivity())
	return []byte(b.String())
}

func renderUserMarkdown(users []*exportedEntity) []byte {
	var b strings.Builder
	for i, ee := range users {
		if i > 0 {
			b.WriteByte('\n')
		}
		fmt.Fprintf(&b, "# %s\n", ee.entity.Title)
		if ee.entity.Summary != "" {
			fmt.Fprintf(&b, "\n%s\n", ee.entity.Summary)
		}
		writeStructuredAttributes(&b, ee)
		writeNoteBlocks(&b, ee.noteBlocks)
	}
	return []byte(b.String())
}

func renderEntityMarkdown(profileName string, ee *exportedEntity) ([]byte, error) {
	fm := entityFrontmatter{
		Title:       ee.entity.Title,
		Aliases:     ee.aliases,
		GeneratedBy: "memstore",
		Profile:     profileName,
		EntityID:    ee.entity.ID,
	}
	fmBytes, err := yaml.Marshal(fm)
	if err != nil {
		return nil, fmt.Errorf("marshal frontmatter for %s: %w", ee.entity.ID, err)
	}

	var b strings.Builder
	b.WriteString("---\n")
	b.Write(fmBytes)
	b.WriteString("---\n\n")
	fmt.Fprintf(&b, "# %s\n", ee.entity.Title)
	if ee.entity.Summary != "" {
		fmt.Fprintf(&b, "\n%s\n", ee.entity.Summary)
	}
	writeStructuredAttributes(&b, ee)
	writeRoutineState(&b, ee.routineState)
	writeNoteBlocks(&b, ee.noteBlocks)
	return []byte(b.String()), nil
}

func writeRoutineState(b *strings.Builder, state map[string]string) {
	if len(state) == 0 {
		return
	}
	keys := make([]string, 0, len(state))
	for k := range state {
		keys = append(keys, k)
	}
	slices.Sort(keys)
	b.WriteString("\n## Routine State\n\n")
	for _, k := range keys {
		fmt.Fprintf(b, "- **%s**: `%s`\n", k, state[k])
	}
}

func writeStructuredAttributes(b *strings.Builder, ee *exportedEntity) {
	hasContacts := ee.contacts != nil && (ee.contacts.Team != "" || ee.contacts.Role != "" || ee.contacts.Timezone != "" || len(ee.contacts.Handles) > 0 || len(ee.contacts.OpenCommitments) > 0)
	if len(ee.facts) == 0 && len(ee.links) == 0 && !hasContacts {
		return
	}

	b.WriteString("\n## Structured Attributes\n\n")
	for _, f := range ee.facts {
		fmt.Fprintf(b, "- **%s**: %s\n", f.Key, formatFactValue(f.ValueJSON))
	}
	if hasContacts {
		writeContactsAttributes(b, ee.contacts)
	}
	for _, l := range ee.links {
		target := "-> " + l.ToEntityID
		if l.ToEntityID == ee.entity.ID {
			target = "<- " + l.FromEntityID
		}
		if l.Note != "" {
			fmt.Fprintf(b, "- **link (%s)**: %s (%s)\n", l.Relation, target, l.Note)
		} else {
			fmt.Fprintf(b, "- **link (%s)**: %s\n", l.Relation, target)
		}
	}
}

func writeContactsAttributes(b *strings.Builder, c *ContactsAttributes) {
	if c.Team != "" {
		fmt.Fprintf(b, "- **team**: %s\n", c.Team)
	}
	if c.Role != "" {
		fmt.Fprintf(b, "- **role**: %s\n", c.Role)
	}
	if c.Timezone != "" {
		fmt.Fprintf(b, "- **timezone**: %s\n", c.Timezone)
	}
	if len(c.Handles) > 0 {
		fmt.Fprintf(b, "- **handles**: %s\n", strings.Join(c.Handles, ", "))
	}
	if len(c.OpenCommitments) > 0 {
		fmt.Fprintf(b, "- **open_commitments**: %s\n", strings.Join(c.OpenCommitments, "; "))
	}
}

func writeNoteBlocks(b *strings.Builder, blocks []NoteBlock) {
	for _, nb := range blocks {
		fmt.Fprintf(b, "\n## %s\n", nb.Heading)
		body := strings.TrimSpace(nb.BodyMD)
		if body != "" {
			fmt.Fprintf(b, "\n%s\n", body)
		}
	}
}

func formatFactValue(raw string) string {
	var v any
	if err := json.Unmarshal([]byte(raw), &v); err != nil {
		return raw
	}
	switch typed := v.(type) {
	case string:
		return typed
	default:
		return raw
	}
}

func renderEpisodicFiles(events []EpisodicEvent) []projectedFile {
	if len(events) == 0 {
		return nil
	}
	grouped := make(map[string][]EpisodicEvent)
	var dates []string
	for _, ev := range events {
		if _, ok := grouped[ev.EventDate]; !ok {
			dates = append(dates, ev.EventDate)
		}
		grouped[ev.EventDate] = append(grouped[ev.EventDate], ev)
	}
	slices.Sort(dates)

	out := make([]projectedFile, 0, len(dates))
	for _, date := range dates {
		var b strings.Builder
		fmt.Fprintf(&b, "# Episodic Log: %s\n\n", date)
		for _, ev := range grouped[date] {
			ts := ev.OccurredAt.UTC().Format("15:04:05Z")
			fmt.Fprintf(&b, "- **%s**", ts)
			if ev.EntityID != "" {
				fmt.Fprintf(&b, " [%s]", ev.EntityID)
			}
			if ev.Channel != "" {
				fmt.Fprintf(&b, " (%s)", ev.Channel)
			}
			fmt.Fprintf(&b, ": %s\n", ev.Summary)
			if details := strings.TrimSpace(ev.DetailsMD); details != "" {
				for _, line := range strings.Split(details, "\n") {
					fmt.Fprintf(&b, "  %s\n", line)
				}
			}
		}
		out = append(out, projectedFile{
			relPath: "episodic/" + date + ".md",
			content: []byte(b.String()),
		})
	}
	return out
}

func syncProjectedFiles(outDir, profileName string, files []projectedFile, now time.Time) (ExportReport, error) {
	if err := os.MkdirAll(outDir, 0o700); err != nil {
		return ExportReport{}, fmt.Errorf("create output directory %s: %w", outDir, err)
	}

	manifestPath := filepath.Join(outDir, manifestFileName)
	oldManifest, err := readManifest(manifestPath)
	if err != nil {
		return ExportReport{}, err
	}

	report := ExportReport{Profile: profileName, OutDir: outDir}
	newFiles, written, unchanged, err := writeProjectedFiles(outDir, files)
	if err != nil {
		return ExportReport{}, err
	}
	report.Written = written
	report.Unchanged = unchanged

	removed, err := removeStaleFiles(outDir, oldManifest.Files, newFiles)
	if err != nil {
		return ExportReport{}, err
	}
	report.Removed = removed

	if oldManifest.Profile != profileName || !manifestEntriesEqual(oldManifest.Files, newFiles) {
		manifest := ProjectionManifest{
			Version:     ProjectionManifestVersion,
			Profile:     profileName,
			GeneratedAt: now,
			Files:       newFiles,
		}
		raw, err := json.MarshalIndent(manifest, "", "  ")
		if err != nil {
			return ExportReport{}, fmt.Errorf("marshal manifest: %w", err)
		}
		if err := writeAtomic(manifestPath, append(raw, '\n')); err != nil {
			return ExportReport{}, err
		}
	}

	return report, nil
}

func writeProjectedFiles(outDir string, files []projectedFile) (map[string]ManifestEntry, int, int, error) {
	newFiles := make(map[string]ManifestEntry, len(files))
	var written, unchanged int
	for _, pf := range files {
		sum := sha256Hex(pf.content)
		newFiles[pf.relPath] = ManifestEntry{
			SHA256:   sum,
			EntityID: pf.entityID,
			Size:     int64(len(pf.content)),
		}
		absPath := filepath.Join(outDir, filepath.FromSlash(pf.relPath))
		existing, readErr := os.ReadFile(absPath)
		if readErr == nil && sha256Hex(existing) == sum {
			unchanged++
			continue
		}
		if readErr != nil && !errors.Is(readErr, fs.ErrNotExist) {
			return nil, 0, 0, fmt.Errorf("read existing %s: %w", absPath, readErr)
		}
		if err := writeAtomic(absPath, pf.content); err != nil {
			return nil, 0, 0, err
		}
		written++
	}
	return newFiles, written, unchanged, nil
}

func removeStaleFiles(outDir string, oldFiles, newFiles map[string]ManifestEntry) (int, error) {
	removed := 0
	for oldRel := range oldFiles {
		if _, keep := newFiles[oldRel]; keep {
			continue
		}
		absPath := filepath.Join(outDir, filepath.FromSlash(oldRel))
		if err := os.Remove(absPath); err != nil {
			if !errors.Is(err, fs.ErrNotExist) {
				return 0, fmt.Errorf("remove stale file %s: %w", absPath, err)
			}
			continue
		}
		removed++
	}
	return removed, nil
}

func readManifest(path string) (ProjectionManifest, error) {
	data, err := os.ReadFile(path)
	if errors.Is(err, fs.ErrNotExist) {
		return ProjectionManifest{}, nil
	}
	if err != nil {
		return ProjectionManifest{}, fmt.Errorf("read manifest %s: %w", path, err)
	}
	var m ProjectionManifest
	if err := json.Unmarshal(data, &m); err != nil {
		return ProjectionManifest{}, fmt.Errorf("parse manifest %s: %w", path, err)
	}
	return m, nil
}

func manifestEntriesEqual(a, b map[string]ManifestEntry) bool {
	if len(a) != len(b) {
		return false
	}
	for k, va := range a {
		if vb, ok := b[k]; !ok || va != vb {
			return false
		}
	}
	return true
}

func writeAtomic(absPath string, data []byte) error {
	dir := filepath.Dir(absPath)
	if err := os.MkdirAll(dir, 0o700); err != nil {
		return fmt.Errorf("create directory %s: %w", dir, err)
	}
	if err := renameio.WriteFile(absPath, data, 0o600, renameio.WithTempDir(dir)); err != nil {
		return fmt.Errorf("write %s: %w", absPath, err)
	}
	return nil
}

func sha256Hex(data []byte) string {
	sum := sha256.Sum256(data)
	return hex.EncodeToString(bytes.Clone(sum[:]))
}

func TestRenderAgentsMDGolden(t *testing.T) {
	raw := `{
  "org": "Acme Desk",
  "rules": [
    {"id": "z-last", "text": "Last alphabetically.", "source": "handbook"},
    {"id": "a-first", "text": "First alphabetically.", "source": "desk guide"}
  ],
  "classes": {
    "review": {
      "description": "Desk reviewers who check proposed changes.",
      "rules": [
        {"id": "cite-line", "text": "Point to the exact line.", "source": "reviewers guide"}
      ]
    }
  }
}`
	spec, err := Decode([]byte(raw))
	if err != nil {
		t.Fatal(err)
	}
	root := t.TempDir()
	diffs, err := RenderAgentsMD(spec, root, false)
	if err != nil {
		t.Fatalf("RenderAgentsMD: %v", err)
	}
	if len(diffs) != 0 {
		t.Fatalf("unexpected diffs: %v", diffs)
	}

	wantOrg := "<!-- Generated by orgctl from the organization spec. Do not edit by hand; the spec is the source of truth. -->\n" +
		"\n" +
		"# Acme Desk — Organization Rules\n" +
		"\n" +
		"## a-first\n\n" +
		"First alphabetically.\n\n" +
		"_Source: desk guide_\n" +
		"\n" +
		"## z-last\n\n" +
		"Last alphabetically.\n\n" +
		"_Source: handbook_\n"

	wantReview := "<!-- Generated by orgctl from the organization spec. Do not edit by hand; the spec is the source of truth. -->\n" +
		"\n" +
		"# Role Class: review\n" +
		"\n" +
		"Desk reviewers who check proposed changes.\n" +
		"\n" +
		"## cite-line\n\n" +
		"Point to the exact line.\n\n" +
		"_Source: reviewers guide_\n"

	cases := []struct {
		rel  string
		want string
	}{
		{"AGENTS.md", wantOrg},
		{"CLAUDE.md", "@AGENTS.md\n"},
		{"roles/review/AGENTS.md", wantReview},
		{"roles/review/CLAUDE.md", "@AGENTS.md\n"},
	}
	for _, tc := range cases {
		got, err := os.ReadFile(filepath.Join(root, filepath.FromSlash(tc.rel)))
		if err != nil {
			t.Fatalf("read %s: %v", tc.rel, err)
		}
		if string(got) != tc.want {
			t.Errorf("%s mismatch:\ngot:\n%s\nwant:\n%s", tc.rel, got, tc.want)
		}
	}
}

func TestRenderAgentsMDIdempotentAndPreservesOtherFiles(t *testing.T) {
	spec := Spec{
		Org:   "Acme",
		Rules: []Rule{{ID: "r1", Text: "Keep it simple.", Source: "handbook"}},
		Classes: map[string]Class{
			"ops": {Description: "Ops", Rules: []Rule{{ID: "ops-1", Text: "Check logs.", Source: "ops"}}},
		},
	}
	root := t.TempDir()
	unrelated := filepath.Join(root, "NOTES.md")
	if err := os.WriteFile(unrelated, []byte("keep me\n"), 0o600); err != nil {
		t.Fatal(err)
	}

	if _, err := RenderAgentsMD(spec, root, false); err != nil {
		t.Fatal(err)
	}

	// Backdate mtime to detect whether a second run rewrites the file.
	past := time.Now().Add(-time.Hour)
	targets := []string{
		filepath.Join(root, "AGENTS.md"),
		filepath.Join(root, "CLAUDE.md"),
		filepath.Join(root, "roles", "ops", "AGENTS.md"),
		filepath.Join(root, "roles", "ops", "CLAUDE.md"),
	}
	for _, p := range targets {
		if err := os.Chtimes(p, past, past); err != nil {
			t.Fatal(err)
		}
	}

	if _, err := RenderAgentsMD(spec, root, false); err != nil {
		t.Fatal(err)
	}
	for _, p := range targets {
		info, err := os.Stat(p)
		if err != nil {
			t.Fatal(err)
		}
		if !info.ModTime().Equal(past) {
			t.Errorf("%s was rewritten on second run: mtime %v, want %v", p, info.ModTime(), past)
		}
	}
	gotUnrelated, err := os.ReadFile(unrelated)
	if err != nil || string(gotUnrelated) != "keep me\n" {
		t.Errorf("unrelated file changed: %q, %v", gotUnrelated, err)
	}
}

func TestRenderAgentsMDCheck(t *testing.T) {
	spec := Spec{
		Org:   "Acme",
		Rules: []Rule{{ID: "r1", Text: "Rule one.", Source: "handbook"}},
		Classes: map[string]Class{
			"ops": {Description: "Ops"},
		},
	}
	root := t.TempDir()

	// Before any render, --check reports all files and writes nothing.
	diffs, err := RenderAgentsMD(spec, root, true)
	if err != nil {
		t.Fatal(err)
	}
	wantAll := []string{"AGENTS.md", "CLAUDE.md", "roles/ops/AGENTS.md", "roles/ops/CLAUDE.md"}
	if !slices.Equal(diffs, wantAll) {
		t.Fatalf("missing diffs = %v, want %v", diffs, wantAll)
	}
	entries, err := os.ReadDir(root)
	if err != nil || len(entries) != 0 {
		t.Fatalf("check wrote files: %v, %v", entries, err)
	}

	// Render, then check passes cleanly.
	if _, err := RenderAgentsMD(spec, root, false); err != nil {
		t.Fatal(err)
	}
	diffs, err = RenderAgentsMD(spec, root, true)
	if err != nil || len(diffs) != 0 {
		t.Fatalf("clean check = %v, %v", diffs, err)
	}

	// Hand edit one file; --check reports only that file and leaves the edit intact.
	opsFile := filepath.Join(root, "roles", "ops", "AGENTS.md")
	if err := os.WriteFile(opsFile, []byte("hand edit\n"), 0o600); err != nil {
		t.Fatal(err)
	}
	diffs, err = RenderAgentsMD(spec, root, true)
	if err != nil {
		t.Fatal(err)
	}
	if !slices.Equal(diffs, []string{"roles/ops/AGENTS.md"}) {
		t.Fatalf("edited diffs = %v", diffs)
	}
	after, err := os.ReadFile(opsFile)
	if err != nil || string(after) != "hand edit\n" {
		t.Fatalf("check overwrote hand edit: %q, %v", after, err)
	}
}

func TestRenderAgentsMDRejectsEscapingClassNames(t *testing.T) {
	for _, bad := range []string{"", "..", "../escape", "a/../b", "/abs", `a\b`, "."} {
		spec := Spec{
			Org:     "Acme",
			Classes: map[string]Class{bad: {Description: "bad"}},
		}
		root := t.TempDir()
		_, err := RenderAgentsMD(spec, root, false)
		if err == nil || !strings.Contains(err.Error(), "invalid class name") {
			t.Errorf("class %q: err = %v, want invalid class name", bad, err)
		}
		entries, readErr := os.ReadDir(root)
		if readErr != nil || len(entries) != 0 {
			t.Errorf("class %q wrote files despite error: %v, %v", bad, entries, readErr)
		}
	}
}

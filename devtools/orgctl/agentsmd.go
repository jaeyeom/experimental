package orgctl

import (
	"bytes"
	"cmp"
	"errors"
	"fmt"
	"io/fs"
	"os"
	"path/filepath"
	"slices"
	"strings"
)

const (
	agentsMDHeader = "<!-- Generated by orgctl from the organization spec. Do not edit by hand; the spec is the source of truth. -->\n"
	claudeMDBody   = "@AGENTS.md\n"
)

type renderedFile struct {
	relPath string
	content []byte
}

// RenderAgentsMD writes (or checks, when check is true) the layered AGENTS.md
// and CLAUDE.md files under root from the decoded spec JSON.
// When check is true, nothing is written and any missing or differing
// relative paths are returned.
func RenderAgentsMD(spec Spec, root string, check bool) ([]string, error) {
	if root == "" {
		return nil, errors.New("render agents-md: root directory is required")
	}
	files, err := planAgentsMDFiles(spec)
	if err != nil {
		return nil, err
	}
	if check {
		var diffs []string
		for _, f := range files {
			target := filepath.Join(root, filepath.FromSlash(f.relPath))
			existing, err := os.ReadFile(target) //nolint:gosec // G304: target is validated under root
			if err != nil {
				if errors.Is(err, fs.ErrNotExist) {
					diffs = append(diffs, f.relPath)
					continue
				}
				return nil, fmt.Errorf("read %s: %w", f.relPath, err)
			}
			if !bytes.Equal(existing, f.content) {
				diffs = append(diffs, f.relPath)
			}
		}
		return diffs, nil
	}
	for _, f := range files {
		target := filepath.Join(root, filepath.FromSlash(f.relPath))
		if err := writeIfChangedAtomic(target, f.content); err != nil {
			return nil, fmt.Errorf("write %s: %w", f.relPath, err)
		}
	}
	return nil, nil
}

func planAgentsMDFiles(spec Spec) ([]renderedFile, error) {
	files := []renderedFile{
		{relPath: "AGENTS.md", content: []byte(renderOrgAgentsMD(spec))},
		{relPath: "CLAUDE.md", content: []byte(claudeMDBody)},
	}
	for _, className := range mapKeys(spec.Classes) {
		if err := validateClassName(className); err != nil {
			return nil, err
		}
		files = append(files,
			renderedFile{
				relPath: "roles/" + className + "/AGENTS.md",
				content: []byte(renderClassAgentsMD(className, spec.Classes[className])),
			},
			renderedFile{
				relPath: "roles/" + className + "/CLAUDE.md",
				content: []byte(claudeMDBody),
			},
		)
	}
	return files, nil
}

func validateClassName(name string) error {
	if name == "" {
		return errors.New("invalid class name: empty")
	}
	if strings.HasPrefix(name, "/") || strings.Contains(name, "\\") || filepath.IsAbs(name) {
		return fmt.Errorf("invalid class name %q: must be relative", name)
	}
	for _, seg := range strings.Split(name, "/") {
		if seg == "" || seg == "." || seg == ".." {
			return fmt.Errorf("invalid class name %q: escapes root", name)
		}
	}
	return nil
}

func renderOrgAgentsMD(spec Spec) string {
	var b strings.Builder
	b.WriteString(agentsMDHeader)
	b.WriteByte('\n')
	title := "Organization Rules"
	if spec.Org != "" {
		title = spec.Org + " — Organization Rules"
	}
	b.WriteString("# ")
	b.WriteString(title)
	b.WriteByte('\n')
	writeRulesSection(&b, spec.Rules)
	return b.String()
}

func renderClassAgentsMD(name string, class Class) string {
	var b strings.Builder
	b.WriteString(agentsMDHeader)
	b.WriteByte('\n')
	b.WriteString("# Role Class: ")
	b.WriteString(name)
	b.WriteByte('\n')
	if desc := strings.TrimRight(normalizeNewlines(class.Description), "\n"); desc != "" {
		b.WriteByte('\n')
		b.WriteString(desc)
		b.WriteByte('\n')
	}
	writeRulesSection(&b, class.Rules)
	return b.String()
}

func writeRulesSection(b *strings.Builder, rules []Rule) {
	sorted := slices.Clone(rules)
	slices.SortFunc(sorted, func(a, c Rule) int {
		return cmp.Compare(a.ID, c.ID)
	})
	for _, rule := range sorted {
		b.WriteByte('\n')
		b.WriteString("## ")
		b.WriteString(rule.ID)
		b.WriteByte('\n')
		b.WriteByte('\n')
		b.WriteString(strings.TrimRight(normalizeNewlines(rule.Text), "\n"))
		b.WriteByte('\n')
		b.WriteByte('\n')
		b.WriteString("_Source: ")
		b.WriteString(strings.TrimRight(normalizeNewlines(rule.Source), "\n"))
		b.WriteString("_\n")
	}
}

func writeIfChangedAtomic(path string, content []byte) error {
	existing, err := os.ReadFile(path) //nolint:gosec // G304: path is validated under root
	if err == nil && bytes.Equal(existing, content) {
		return nil
	}
	if err != nil && !errors.Is(err, fs.ErrNotExist) {
		return fmt.Errorf("read existing: %w", err)
	}
	dir := filepath.Dir(path)
	if err := os.MkdirAll(dir, 0o750); err != nil {
		return fmt.Errorf("mkdir: %w", err)
	}
	tmp, err := os.CreateTemp(dir, ".orgctl-*")
	if err != nil {
		return fmt.Errorf("create temp: %w", err)
	}
	tmpName := tmp.Name()
	cleanup := true
	defer func() {
		if cleanup {
			_ = os.Remove(tmpName)
		}
	}()
	if _, err := tmp.Write(content); err != nil {
		_ = tmp.Close()
		return fmt.Errorf("write temp: %w", err)
	}
	if err := tmp.Chmod(0o600); err != nil {
		_ = tmp.Close()
		return fmt.Errorf("chmod temp: %w", err)
	}
	if err := tmp.Close(); err != nil {
		return fmt.Errorf("close temp: %w", err)
	}
	if err := os.Rename(tmpName, path); err != nil {
		return fmt.Errorf("rename temp: %w", err)
	}
	cleanup = false
	return nil
}

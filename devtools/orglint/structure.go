package orglint

import (
	"fmt"
	"regexp"
	"strconv"
	"strings"
)

var structureCheckers = []Checker{
	{"invalid-block", checkInvalidBlock},
	{"incomplete-drawer", checkIncompleteDrawer},
	{"misplaced-heading", checkMisplacedHeading},
	{"misplaced-planning-info", checkMisplacedPlanning},
	{"obsolete-properties-drawer", checkObsoletePropertiesDrawer},
	{"special-property-in-properties-drawer", checkSpecialProperty},
	{"invalid-id-property", checkInvalidID},
	{"spurious-colons", checkSpuriousColons},
	{"invalid-keyword-syntax", checkKeywordSyntax},
	{"item-number", checkItemNumber},
	{"orphaned-affiliated-keywords", checkOrphanedAffiliated},
}

var (
	blockLineRE     = regexp.MustCompile(`(?i)^[ \t]*#\+(BEGIN|END)(?::|_\S*)?[ \t]*`)
	dynamicRE       = regexp.MustCompile(`(?i)^[ \t]*#\+(BEGIN|END):`)
	drawerLineRE    = regexp.MustCompile(`^[ \t]*:([-_\w]+):[ \t]*$`)
	planningLineRE  = regexp.MustCompile(`(?i)^[ \t]*(?:CLOSED|DEADLINE|SCHEDULED):`)
	misplacedRE     = regexp.MustCompile(`[^*\n\r ,]\*\*+ `)
	spuriousTagsRE  = regexp.MustCompile(`[ \t]+:([\p{L}\p{N}_@#%:]+):[ \t]*$`)
	keywordSyntaxRE = regexp.MustCompile(`^[ \t]*#\+([^\s:]*)(?: |$)`)
	dualKeywordRE   = regexp.MustCompile(`(?i)^[ \t]*#\+(?:CAPTION|RESULTS)(?:\[.*\])?:(?: |$)`)
	numberedItemRE  = regexp.MustCompile(`^([ \t]*)(\d+[.)])([ \t]+|$)(?:\[@(?:\d+|[A-Za-z])\])?`)
	counterRE       = regexp.MustCompile(`^[ \t]*\d+[.)](?:[ \t]+)\[@(\d+|[A-Za-z])\]`)
	attrKeywordRE   = regexp.MustCompile(`(?i)^ATTR_[-_A-Za-z0-9]+$`)
)

var specialProperties = map[string]bool{
	"ALLTAGS": true, "BLOCKED": true, "CLOCKSUM": true, "CLOCKSUM_T": true,
	"CLOSED": true, "DEADLINE": true, "FILE": true, "ITEM": true,
	"PRIORITY": true, "SCHEDULED": true, "TAGS": true, "TIMESTAMP": true,
	"TIMESTAMP_IA": true, "TODO": true,
}

// orphanable are the affiliated keywords that org-lint reports when they are
// not followed by an element. RESULT and RESULTS are generated by Babel and
// are left alone.
var orphanable = map[string]bool{
	"CAPTION": true, "DATA": true, "HEADER": true, "HEADERS": true,
	"LABEL": true, "NAME": true, "PLOT": true, "RESNAME": true,
	"SOURCE": true, "SRCNAME": true, "TBLNAME": true,
}

// inBlock reports whether line n is inside a closed block, delimiters
// included. If raw is true, only blocks whose contents are not parsed as org
// count.
func (d *Document) inBlock(n int, raw bool) bool {
	for _, b := range d.Blocks {
		if b.EndLine == 0 || n < b.Line || n > b.EndLine {
			continue
		}
		switch b.Name {
		case "COMMENT", "EXAMPLE", "EXPORT", "SRC", "VERSE":
			return true
		}
		if !raw {
			return true
		}
	}
	return false
}

// closedDrawer returns the closed drawer that starts on line n.
func (d *Document) closedDrawer(n int) *Drawer {
	for i := range d.Drawers {
		if d.Drawers[i].Line == n && d.Drawers[i].EndLine > 0 {
			return &d.Drawers[i]
		}
	}
	return nil
}

func (d *Document) isHeadlineLine(n int) bool {
	for _, h := range d.Headlines {
		if h.Line == n {
			return true
		}
	}
	return false
}

// isPropertyDrawer reports whether dr is a real property drawer: it directly
// follows a headline (optionally with one planning line in between), or, in
// the first section, only comments and keywords precede it.
func (d *Document) isPropertyDrawer(dr Drawer) bool {
	if !strings.EqualFold(dr.Name, "PROPERTIES") || dr.EndLine == 0 {
		return false
	}
	prev := dr.Line - 1
	if prev >= 1 && planningLineRE.MatchString(d.Lines[prev-1]) {
		prev--
	}
	if prev >= 1 && d.isHeadlineLine(prev) {
		return true
	}
	if len(d.Headlines) > 0 && d.Headlines[0].Line < dr.Line {
		return false
	}
	for i := 0; i < dr.Line-1; i++ {
		t := strings.TrimSpace(d.Lines[i])
		if t != "" && !strings.HasPrefix(t, "# ") && t != "#" && !strings.HasPrefix(t, "#+") {
			return false
		}
	}
	return true
}

func (d *Document) propertyDrawers() []Drawer {
	var out []Drawer
	for _, dr := range d.Drawers {
		if d.isPropertyDrawer(dr) {
			out = append(out, dr)
		}
	}
	return out
}

func checkInvalidBlock(d *Document) []Finding {
	var out []Finding
	for i, text := range d.Lines {
		n := i + 1
		m := blockLineRE.FindStringSubmatch(text)
		if m == nil {
			continue
		}
		name := strings.TrimSpace(text)
		atEOL := len(m[0]) == len(text)
		switch {
		case strings.EqualFold(m[1], "END") && !atEOL:
			out = append(out, Finding{Line: n, Message: fmt.Sprintf("Invalid block closing line %q", name)})
		case d.inBlock(n, false) || dynamicBlock(d, n):
		default:
			out = append(out, Finding{Line: n, Message: fmt.Sprintf("Possible incomplete block %q", name)})
		}
	}
	return out
}

// dynamicBlock reports whether line n is the "#+BEGIN: name" or "#+END:"
// line of a dynamic block that is closed.
func dynamicBlock(d *Document, n int) bool {
	m := dynamicRE.FindStringSubmatch(d.Lines[n-1])
	if m == nil {
		return false
	}
	if strings.EqualFold(m[1], "BEGIN") {
		for _, l := range d.Lines[n:] {
			if dm := dynamicRE.FindStringSubmatch(l); dm != nil && strings.EqualFold(dm[1], "END") {
				return true
			}
		}
		return false
	}
	for i := n - 2; i >= 0; i-- {
		if dm := dynamicRE.FindStringSubmatch(d.Lines[i]); dm != nil && strings.EqualFold(dm[1], "BEGIN") {
			return true
		}
	}
	return false
}

func checkIncompleteDrawer(d *Document) []Finding {
	var out []Finding
	for n := 1; n <= len(d.Lines); n++ {
		text := d.Lines[n-1]
		if !drawerLineRE.MatchString(text) || d.inBlock(n, true) {
			continue
		}
		dr := d.closedDrawer(n)
		switch {
		case dr == nil:
			out = append(out, Finding{Line: n, Message: fmt.Sprintf("Possible incomplete drawer %q", strings.TrimSpace(text))})
		case d.isPropertyDrawer(*dr):
			n = dr.EndLine
		default:
			for k := dr.Line + 1; k < dr.EndLine; k++ {
				if drawerLineRE.MatchString(d.Lines[k-1]) {
					out = append(out, Finding{Line: k, Message: fmt.Sprintf("Possible misleading drawer entry %q", strings.TrimSpace(d.Lines[k-1]))})
				}
			}
			n = dr.EndLine
		}
	}
	return out
}

// paragraphBreak reports whether the line starts an element other than a
// paragraph continuation.
func (d *Document) paragraphBreak(n int) bool {
	t := d.Lines[n-1]
	return d.isHeadlineLine(n) || blockLineRE.MatchString(t) || keywordRE.MatchString(t) ||
		itemRE.MatchString(t) || drawerLineRE.MatchString(t)
}

func checkMisplacedHeading(d *Document) []Finding {
	var out []Finding
	for n := 1; n <= len(d.Lines); n++ {
		text := d.Lines[n-1]
		t := strings.TrimLeft(text, " \t")
		if d.inBlock(n, true) || strings.HasPrefix(t, "#") || strings.HasPrefix(t, ": ") ||
			strings.HasPrefix(t, "|") || planningLineRE.MatchString(text) {
			continue
		}
		for range misplacedRE.FindAllStringIndex(text, -1) {
			out = append(out, Finding{Line: d.misplacedHeadingLine(n), Message: "Possibly misplaced heading line"})
		}
	}
	return out
}

// misplacedHeadingLine mimics where Emacs puts the report. org-lint uses the
// match data left behind by the element parser instead of the match itself,
// which is the line after the paragraph when a blank line or the end of the
// buffer ends it and the start of the paragraph otherwise.
func (d *Document) misplacedHeadingLine(n int) int {
	if d.isHeadlineLine(n) {
		return n
	}
	end := n + 1
	for end <= len(d.Lines) && strings.TrimSpace(d.Lines[end-1]) != "" && !d.paragraphBreak(end) {
		end++
	}
	if end > len(d.Lines) || strings.TrimSpace(d.Lines[end-1]) == "" {
		return end
	}
	start := n
	for start > 1 && strings.TrimSpace(d.Lines[start-2]) != "" && !d.paragraphBreak(start) {
		start--
	}
	return start
}

func checkMisplacedPlanning(d *Document) []Finding {
	var out []Finding
	for n := 1; n <= len(d.Lines); n++ {
		if !planningLineRE.MatchString(d.Lines[n-1]) || d.inBlock(n, true) {
			continue
		}
		if n > 1 && d.isHeadlineLine(n-1) {
			continue // a real planning line
		}
		out = append(out, Finding{Line: n, Message: "Misplaced planning info line"})
	}
	return out
}

func checkObsoletePropertiesDrawer(d *Document) []Finding {
	var out []Finding
	for _, dr := range d.Drawers {
		if strings.EqualFold(dr.Name, "PROPERTIES") && dr.EndLine > 0 && !d.isPropertyDrawer(dr) && !d.inBlock(dr.Line, true) {
			out = append(out, Finding{Line: dr.Line, Message: "Incorrect contents for PROPERTIES drawer"})
		}
	}
	return out
}

func checkSpecialProperty(d *Document) []Finding {
	var out []Finding
	for _, dr := range d.propertyDrawers() {
		for _, p := range dr.Properties {
			if specialProperties[strings.ToUpper(p.Name)] {
				out = append(out, Finding{Line: p.Line, Message: fmt.Sprintf("Special property %q found in a properties drawer", p.Name)})
			}
		}
	}
	return out
}

func checkInvalidID(d *Document) []Finding {
	var out []Finding
	for _, dr := range d.propertyDrawers() {
		for _, p := range dr.Properties {
			if p.Name == "ID" && strings.Contains(p.Value, "::") {
				out = append(out, Finding{Line: p.Line, Message: `IDs should not include "::": ` + elispQuote(p.Value)})
			}
		}
	}
	return out
}

// elispQuote formats s like Emacs's %S.
func elispQuote(s string) string {
	return `"` + strings.NewReplacer(`\`, `\\`, `"`, `\"`).Replace(s) + `"`
}

func checkSpuriousColons(d *Document) []Finding {
	var out []Finding
	for _, h := range d.Headlines {
		if m := spuriousTagsRE.FindStringSubmatch(d.Lines[h.Line-1]); m != nil && strings.Contains(m[0], "::") {
			out = append(out, Finding{Line: h.Line, Message: "Tags contain a spurious colon"})
		}
	}
	return out
}

func checkKeywordSyntax(d *Document) []Finding {
	var out []Finding
	for i, text := range d.Lines {
		m := keywordSyntaxRE.FindStringSubmatch(text)
		if m == nil {
			continue
		}
		up := strings.ToUpper(m[1])
		if strings.HasPrefix(up, "BEGIN") || strings.HasPrefix(up, "END") || dualKeywordRE.MatchString(text) {
			continue
		}
		out = append(out, Finding{Line: i + 1, Message: fmt.Sprintf("Possible missing colon in keyword %q", m[1])})
	}
	return out
}

// listEntry is an ordered list item being tracked while walking the lists.
type listEntry struct {
	indent  int
	counter int // number of the last item, honoring [@N] counters
}

func checkItemNumber(d *Document) []Finding {
	var out []Finding
	var stack []listEntry
	prev := 0
	for _, it := range d.Items {
		stack = d.endLists(stack, prev, it.Line)
		prev = it.Line
		for len(stack) > 0 && stack[len(stack)-1].indent > it.Indent {
			stack = stack[:len(stack)-1]
		}
		if len(stack) == 0 || stack[len(stack)-1].indent < it.Indent {
			stack = append(stack, listEntry{indent: it.Indent})
		}
		top := &stack[len(stack)-1]
		top.counter++
		text := d.Lines[it.Line-1]
		if c := counterRE.FindStringSubmatch(text); c != nil {
			top.counter = counterValue(c[1])
			continue
		}
		m := numberedItemRE.FindStringSubmatch(text)
		if m == nil {
			continue
		}
		bullet := m[2] + m[3]
		num, _ := strconv.Atoi(strings.TrimRight(m[2], ".)"))
		if num != top.counter {
			out = append(out, Finding{Line: it.Line, Message: fmt.Sprintf(
				"Bullet counter %q is not the same with item position %d.  Consider adding manual [@%d] counter.",
				bullet, top.counter, num)})
		}
	}
	return out
}

func counterValue(s string) int {
	if n, err := strconv.Atoi(s); err == nil {
		return n
	}
	return int(strings.ToUpper(s)[0]) - 64
}

// endLists drops the lists that end between lines from and to, the lines of
// two consecutive items: a headline, two blank lines, or a line indented no
// deeper than an item.
func (d *Document) endLists(stack []listEntry, from, to int) []listEntry {
	blanks := 0
	for n := from + 1; n < to && len(stack) > 0; n++ {
		text := d.Lines[n-1]
		if strings.TrimSpace(text) == "" {
			if blanks++; blanks == 2 {
				return nil
			}
			continue
		}
		blanks = 0
		if d.isHeadlineLine(n) {
			return nil
		}
		indent := len(text) - len(strings.TrimLeft(text, " \t"))
		for len(stack) > 0 && stack[len(stack)-1].indent >= indent {
			stack = stack[:len(stack)-1]
		}
	}
	return stack
}

func checkOrphanedAffiliated(d *Document) []Finding {
	var out []Finding
	for i, k := range d.Keywords {
		key, _, _ := strings.Cut(k.Key, "[")
		if !orphanable[key] && !attrKeywordRE.MatchString(key) {
			continue
		}
		if d.keywordOrphaned(i) {
			out = append(out, Finding{Line: k.Line, Message: fmt.Sprintf("Orphaned affiliated keyword: %q", key)})
		}
	}
	return out
}

// keywordOrphaned reports whether the affiliated keyword i is not followed by
// an element it could attach to.
func (d *Document) keywordOrphaned(i int) bool {
	n := d.Keywords[i].Line + 1
	for n <= len(d.Lines) {
		text := d.Lines[n-1]
		switch {
		case strings.TrimSpace(text) == "", d.isHeadlineLine(n):
			return true
		case strings.EqualFold(strings.TrimSpace(text), ":END:"), endRE.MatchString(text):
			return true
		}
		m := keywordRE.FindStringSubmatch(text)
		if m == nil {
			return false
		}
		key, _, _ := strings.Cut(strings.ToUpper(m[1]), "[")
		if !orphanable[key] && !attrKeywordRE.MatchString(key) && key != "RESULTS" && key != "RESULT" {
			return false
		}
		n++
	}
	return true
}
